import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { BlobsServer } from '@netlify/blobs/server';
import { getStore } from '@netlify/blobs';
import { settings,loginHandler,logoutHandler,vaultHandler,authorize,limitLogin,makeSession,HttpError } from '../netlify/lib/core.mjs';
import { initialNotebook,newSalt,deriveKey,encrypt,decrypt } from '../src/model.ts';
const config={password:'test-only-vetvi-password',secret:'test-only-session-secret-0123456789abcdef'};
const origin='https://test.example';
function req(path,method='GET',body,cookie='',source=origin){return new Request(origin+path,{method,headers:{'Content-Type':'application/json','Origin':source,Cookie:cookie},body:body===undefined?undefined:JSON.stringify(body)});}
const isStatus=status=>error=>error instanceof HttpError&&error.status===status;
test('password, encrypted notes, access control and persistent Blobs',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'vetvi-blobs-test-'));
  const server=new BlobsServer({directory,token:'local-test-token',logger:()=>{}});
  const address=await server.start();t.after(()=>server.stop());
  const store=getStore({name:'vetvi-test',siteID:'local-test',token:'local-test-token',apiURL:address.address,consistency:'strong'});
  assert.throws(()=>settings({}),isStatus(503));
  await assert.rejects(()=>vaultHandler(req('/api/vault'),store,config),isStatus(401));
  await assert.rejects(()=>vaultHandler(req('/api/vault','PUT',{revision:0}),store,config),isStatus(401));
  await assert.rejects(()=>loginHandler(req('/api/login','POST',{password:config.password},'','https://evil.example'),store,config,'a'),isStatus(403));
  await assert.rejects(()=>loginHandler(req('/api/login','POST',{password:'wrong'}),store,config,'a'),isStatus(401));
  const login=await loginHandler(req('/api/login','POST',{password:config.password}),store,config,'a');
  const header=login.headers.get('set-cookie');assert.match(header,/HttpOnly/);assert.match(header,/Secure/);assert.match(header,/SameSite=Strict/);
  const cookie=header.split(';')[0];
  assert.deepEqual(await (await vaultHandler(req('/api/vault','GET',undefined,cookie),store,config)).json(),{payload:null,revision:0});
  const book=initialNotebook(),salt=newSalt(),key=await deriveKey(config.password,salt),payload=await encrypt(book,key,salt);
  assert.deepEqual(await decrypt(payload,key),book);
  await assert.rejects(()=>deriveKey('wrong',salt).then(k=>decrypt(payload,k)));
  const saved=await vaultHandler(req('/api/vault','PUT',{payload,revision:0},cookie),store,config);assert.equal((await saved.json()).revision,1);
  const loaded=await (await vaultHandler(req('/api/vault','GET',undefined,cookie),store,config)).json();assert.deepEqual(await decrypt(loaded.payload,key),book);
  assert.ok(!JSON.stringify(loaded).includes('Моё пространство'));
  await assert.rejects(()=>vaultHandler(req('/api/vault','PUT',{payload,revision:0},cookie),store,config),isStatus(409));
  await assert.rejects(()=>vaultHandler(req('/api/vault','PUT',{payload:{},revision:1},cookie),store,config),isStatus(400));
  const updated=await vaultHandler(req('/api/vault','PUT',{payload,revision:1},cookie),store,config);assert.equal((await updated.json()).revision,2);
  const expired='vetvi_session='+makeSession(config,Date.now()-13*3600_000);
  await assert.rejects(()=>authorize(req('/api/vault','GET',undefined,expired),store,config),isStatus(401));
  await assert.rejects(()=>authorize(req('/api/vault','GET',undefined,cookie.slice(0,-1)+'!'),store,config),isStatus(401));
  await logoutHandler(req('/api/logout','POST',{},cookie),store,config);
  await assert.rejects(()=>vaultHandler(req('/api/vault','GET',undefined,cookie),store,config),isStatus(401));
  for(let i=0;i<10;i++)await limitLogin(store,'limited');
  await assert.rejects(()=>limitLogin(store,'limited'),isStatus(429));
});
